import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844}});
const payloads=[];
let fail=true;
await context.route('**/*', route=>{
 const url=new URL(route.request().url());
 if(url.hostname==='127.0.0.1') return route.continue();
 if(route.request().method()==='POST'&&url.hostname==='fdoy7mjmtd.execute-api.eu-central-1.amazonaws.com') {
  payloads.push(route.request().postDataJSON());
  return route.fulfill({status:fail?500:200,contentType:'application/json',body:'{}',headers:{'access-control-allow-origin':'*'}});
 }
 return route.abort();
});
const page=await context.newPage();
const results=[];
for(const slug of ['wdrozenie-ai','aplikacje-i-systemy','cofounder-as-a-service']) {
 await page.goto(`http://127.0.0.1:4330/pl/uslugi/${slug}/?utm_source=qa&utm_campaign=service-review`,{waitUntil:'networkidle'});
 if(await page.locator('#cookieReject').isVisible()) await page.locator('#cookieReject').click();
 await page.waitForTimeout(700);
 await page.mouse.move(10,200);
 const button=await page.locator('.hero .btn').boundingBox();
 await page.mouse.move(button.x+button.width/2,button.y+button.height/2);
 await page.waitForTimeout(400);
 const cursor=await page.locator('.cur').evaluate(e=>({opacity:getComputedStyle(e).opacity,width:e.getBoundingClientRect().width}));
 assert.equal(cursor.opacity,'1'); assert.ok(cursor.width>30,`W5 dot grows over CTA: ${slug} ${JSON.stringify(cursor)}`);
 await page.keyboard.press('Tab');
 assert.equal(await page.locator('.cur').evaluate(e=>getComputedStyle(e).opacity),'0');
 await page.locator('.hero .btn').focus();
 const focus=await page.locator('.hero .btn').evaluate(e=>({style:getComputedStyle(e).outlineStyle,color:getComputedStyle(e).outlineColor}));
 assert.equal(focus.style,'solid');
 await page.keyboard.press('Enter');
 await page.waitForURL(url => url.hash === '#ctForm');
 if(slug==='cofounder-as-a-service') assert.ok(page.url().includes('service=Cofounder'));
 await page.locator('[name="name"]').fill('Syntetyczny test');
 await page.locator('[name="email"]').fill('test@example.com');
 await page.locator('[name="message"]').fill('Opis syntetyczny. Nie wysyłać.');
 await page.locator('[name="consent"]').check();
 fail=true;
 await page.locator('#ctForm button[type="submit"]').click();
 await page.locator('#ctMsg').filter({hasText:'kacper@mioduszewsky.com'}).waitFor();
 assert.equal(await page.locator('#ctForm button[type="submit"]').isEnabled(),true);
 fail=false;
 await page.locator('#ctForm button[type="submit"]').click();
 await page.locator('#ctSuccess').waitFor({state:'visible'});
 const payload=payloads.at(-1);
 assert.match(payload.message,/utm_source=qa/);assert.match(payload.message,/utm_campaign=service-review/);
 assert.match(payload.message,/\[Usługa\]/);
 results.push({slug,focus,success:true,errorRecovered:true,payload});
}
await page.goto('http://127.0.0.1:4330/pl/uslugi/aplikacje-i-systemy/?edit=1',{waitUntil:'networkidle'});
await page.locator('#copy-toggle').click();
assert.equal(await page.locator('h1').getAttribute('contenteditable'),'plaintext-only');
await page.locator('h1').fill('Test edycji lokalnej');
const downloadPromise=page.waitForEvent('download');await page.locator('#copy-export').click();
const download=await downloadPromise; await download.saveAs('/tmp/service-landings-review/copy-editor-test.json');
results.push({editor:'editable, export downloaded'});
await page.goto('http://127.0.0.1:4330/pl/uslugi/aplikacje-i-systemy/',{waitUntil:'networkidle'});
assert.match(await page.locator('h1').innerText(),/Zbuduj własną aplikację/);
await context.close();
const nojs=await browser.newContext({javaScriptEnabled:false,viewport:{width:320,height:740}});
await nojs.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
const p=await nojs.newPage();await p.goto('http://127.0.0.1:4330/pl/uslugi/wdrozenie-ai/');
assert.equal(await p.locator('h1').isVisible(),true);assert.equal(await p.locator('.hero .btn').isVisible(),true);
results.push({noJs:'content and navigation visible'});
await browser.close();await writeFile('/tmp/service-landings-review/interactions.json',JSON.stringify(results,null,2));
console.log('PASS: 3 keyboard CTA paths, focus, UTM across navigation, failure + retry + success (mocked), editor/export, no-JS content.');
